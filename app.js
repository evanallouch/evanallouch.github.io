function translateAttributes() {
  document.querySelectorAll('[data-i18n-aria]').forEach(element => element.setAttribute('aria-label', t(element.dataset.i18nAria)));
  document.querySelectorAll('[data-i18n-alt]').forEach(element => element.alt = t(element.dataset.i18nAlt));
}

function setLanguage(lang, updateHistory) {
  if (!copy[lang]) return;
  language = lang;
  document.documentElement.lang = lang;
  document.title = t('pageTitle');
  document.querySelectorAll('[data-i18n]').forEach(element => element.innerHTML = t(element.dataset.i18n));
  translateAttributes();
  document.querySelectorAll('[data-lang]').forEach(element => {
    if (element.dataset.lang === lang) element.setAttribute('aria-current', 'page');
    else element.removeAttribute('aria-current');
  });
  const portfolioPath = 'assets/Evan_Allouch_Portfolio_' + (lang === 'fr' ? 'FR' : 'US') + '_2027.pdf';
  document.querySelectorAll('.portfolio-link').forEach(element => element.href = portfolioPath);
  document.querySelector('.hero-image-button').setAttribute('aria-label', t('watchNomade'));
  menuButton.setAttribute('aria-label', t(menuButton.getAttribute('aria-expanded') === 'true' ? 'menuClose' : 'menuOpen'));
  document.querySelector('meta[name="description"]').content = t('metaDescription');
  document.querySelector('meta[property="og:title"]').content = t('pageTitle');
  document.querySelector('meta[property="og:site_name"]').content = t('siteName');
  document.querySelector('meta[property="og:description"]').content = t('metaDescription');
  document.querySelector('meta[property="og:locale"]').content = lang === 'fr' ? 'fr_FR' : 'en_US';
  document.querySelector('meta[name="twitter:title"]').content = t('pageTitle');
  document.querySelector('meta[name="twitter:description"]').content = t('metaDescription');
  document.querySelector('meta[property="og:image:alt"]').content = t('heroAlt');
  document.querySelector('meta[name="twitter:image:alt"]').content = t('heroAlt');
  const canonical = 'https://evanallouch.github.io/' + (lang === 'fr' ? 'fr.html' : '');
  document.querySelector('link[rel="canonical"]').href = canonical;
  document.querySelector('meta[property="og:url"]').content = canonical;
  document.getElementById('copy-status').textContent = '';
  renderFilms();
  if (dialog.open && currentFilm) renderDialog();
  if (updateHistory) {
    const path = (lang === 'fr' ? 'fr.html' : './') + window.location.hash;
    window.history.replaceState({ language: lang }, '', path);
  }
}

