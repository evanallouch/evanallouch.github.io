document.addEventListener('click', event => {
  const lang = event.target.closest('[data-lang]');
  if (lang) {
    event.preventDefault();
    setLanguage(lang.dataset.lang, true);
    return;
  }
  const filter = event.target.closest('[data-filter]');
  if (filter) {
    currentFilter = filter.dataset.filter;
    document.querySelectorAll('[data-filter]').forEach(button => button.setAttribute('aria-pressed', String(button === filter)));
    renderFilms();
    return;
  }
  const filmLink = event.target.closest('[data-film]');
  if (filmLink) {
    if (event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
    event.preventDefault();
    openFilm(filmLink.dataset.film, filmLink, filmLink.dataset.startChapter);
    return;
  }
  const chapter = event.target.closest('[data-chapter]');
  if (chapter) {
    currentChapter = chapter.dataset.chapter;
    renderDialog();
    dialog.querySelector('[data-chapter="' + currentChapter + '"]').focus();
    return;
  }
  const next = event.target.closest('[data-next-film]');
  if (next) {
    currentFilm = next.dataset.nextFilm;
    currentChapter = 'main';
    renderDialog();
    dialog.scrollTop = 0;
    document.querySelector('.close-dialog').focus();
    return;
  }
  const load = event.target.closest('[data-load-video]');
  if (load) {
    const film = films.find(item => item.id === currentFilm);
    const allowedVideos = films.flatMap(item => [item.video, item.preview].filter(Boolean));
    if (!allowedVideos.includes(load.dataset.loadVideo)) return;
    const frame = document.createElement('iframe');
    const status = film.captions && film.captions[currentChapter];
    frame.src = 'https://www.youtube-nocookie.com/embed/' + load.dataset.loadVideo + '?autoplay=1&rel=0&playsinline=1&hl=' + language + (status === 'english' ? '&cc_load_policy=1&cc_lang_pref=en' : '');
    frame.title = film.title + ' — ' + t('screeningRoom');
    frame.allow = 'accelerometer; autoplay; encrypted-media; gyroscope; picture-in-picture; web-share';
    frame.allowFullscreen = true;
    frame.referrerPolicy = 'strict-origin-when-cross-origin';
    load.parentElement.replaceChildren(frame);
    return;
  }
  if (menuButton.getAttribute('aria-expanded') === 'true' && !event.target.closest('.site-header')) closeMenu();
});

